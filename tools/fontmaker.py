def build(name, glyphs, height):
    widths, rows = [], []
    for code in range(32, 127):
        g = glyphs.get(chr(code))
        if g is None:
            raise SystemExit("%s: no glyph for %r" % (name, chr(code)))
        skip = g[0] if isinstance(g[0], int) else 0
        art = g[1:] if skip else g
        w = max(len(r) for r in art)
        if w > 8 or skip + len(art) > height:
            raise SystemExit("%s: %r too big" % (name, chr(code)))
        bits = [0] * height
        for i, r in enumerate(art):
            if len(r) != w:
                raise SystemExit("%s: %r ragged row %r" % (name, chr(code), r))
            v = 0
            for c, ch in enumerate(r):
                if ch == "#":
                    v |= 0x80 >> c
            bits[skip + i] = v
        widths.append(w)
        rows.append(bits)
    out = ["static const uint8_t %s_w[95] = {" % name]
    for i in range(0, 95, 16):
        out.append("    " + ", ".join(str(w) for w in widths[i : i + 16]) + ",")
    out.append("};")
    out.append("static const uint8_t %s_bits[95 * %d] = {" % (name, height))
    for code, b in zip(range(32, 127), rows):
        c = chr(code)
        label = {"\\": "backslash"}.get(c, c)
        out.append("    " + ", ".join("0x%02X" % v for v in b) + ", /* %s */" % label)
    out.append("};")
    out.append("const pfont_t %s = {%d, %s_w, %s_bits};" % (name, height, name, name))
    return "\n".join(out)


